/* ===== 提示词模板：全部集中管理，换模型 / 调策略只改这里 ===== */
(function () {
  "use strict";

  function langOf(b) {
    if (b.msgLang) return b.msgLang;
    if (b.country === "巴西") return "葡萄牙语（巴西）";
    if (b.country === "中国") return "中文";
    return "英语";
  }

  window.Prompts = {
    langOf: langOf,

    translate: "任务：把下面的客户消息翻译成简体中文（给中国卖家看）。商务术语保留原文（如 FOB、MOQ、PI、CE、IP65、20GP、40HQ）。输出严格 JSON：{\"zh\":\"...\"}，不要输出任何其他文字。",

    extract: "任务：从下面的客户消息中提取业务字段。规则：1) 只提取消息中明确出现的信息，未提及的字段不输出；2) 数值必须以原文为准，不得推算；3) k 取值限定为：数量、目标价、交期、认证、物流、顾虑、决策进度、关系信号；4) v 用简体中文书写（商务术语保留原文），不得照抄外语原句——客户索要某物时，\"顾虑/决策进度\"写中文概括（如\"等待书包视频\"），\"目标价\"只在客户给出具体数字时提取（索要报价行为本身不是目标价）。输出严格 JSON：{\"fields\":[{\"k\":\"...\",\"v\":\"...\"}]}；没有任何字段时输出 {\"fields\":[]}。",

    intent: "任务：判断这条客户消息对谈单意向的信号价值。输出严格 JSON：{\"delta\":整数,-10到15,\"reason\":\"不超过8个汉字\"}。参考标准：明确新数量/新交期/付款条件 +10~15；索要报价/样品/装柜量 +8；确认工厂身份/大单意向 +8；砍价/在比价 -5；长期未回复/明确拒绝 -10~-5；普通寒暄 0。注意：客户档案中已知的信息不算新信号，只判断本条消息相对档案的增量；仅重复确认已知信息时 delta ≤ 3。",

    suggest: function (b) {
      var stage = (window.Mock && Mock.STAGES) ? Mock.STAGES[b.stage] : "";
      var style = b.profile ? "客户国家画像（称呼/风格）：" + b.profile.address + " / " + b.profile.style + "；" : "";
      return "背景：你代表中国的出口供应商/工厂，正在 WhatsApp 上跟采购商「" + b.name + "」谈单。\n" +
        "任务：生成 3 条可以直接发给客户的回复。\n" +
        "铁律A【语言】：text 字段必须全部用" + langOf(b) + "书写，text 中严禁出现任何中文汉字；只有 zh 字段允许用中文。\n" +
        "铁律B【绝不瞎编】：先判断信息量，再决定说什么：\n" +
        "1) 只用「客户档案」和「最近对话」里真实出现的信息。其中没有的产品/规格/认证（CE、INMETRO 等）/箱型（20GP、40HQ）/价格/数量/交期/付款条款，一律不要主动提，更不要编造；宁可少说。\n" +
        "2) 按当前阶段「" + (stage || "询盘") + "」定深浅：若刚认识、还没聊具体产品（询盘/需求确认期），只写简短自然的开场或了解需求的问句（在找什么产品、大概数量、目标市场），不堆卖点、不报价、不谈认证/箱型/付款。\n" +
        "3) 术语 FOB/MOQ/PI/CE/INMETRO/IP65/20GP/40HQ 仅当它已出现在档案或对话中才可沿用（保留原文不翻译），否则禁止出现。\n" +
        "4) 语气像真人 WhatsApp：口语、简短（每条≤50词）、每条结尾只有一个行动点（一个问题或一个动作），别像群发模板，别用 as soon as possible 之类空话。\n" +
        "5) 用" + langOf(b) + "书写。" + style + "\n" +
        "6) 3 条给不同切入点/口吻，但都要符合当前信息量（信息少时三条都应是轻量开场，只是角度不同）。\n" +
        "7) 每条附 zh 字段＝该条的中文意思（口语、准确）。\n" +
        "输出严格 JSON：{\"suggestions\":[{\"style\":\"6字内中文标签\",\"text\":\"回复正文\",\"zh\":\"该条的中文意思\"}]}";
    },

    localize: function (b) {
      var style = b.profile ? "6) 语气符合该客户国家商务习惯：" + b.profile.style + "；提示：" + b.profile.tip + "；" : "6) 语气专业、友好；";
       return "任务：把下面卖家写的中文，改写成可直接发给客户的一条消息。要求：" +
         "1) 全部用" + langOf(b) + "书写，输出中严禁出现任何中文汉字；" +
        "2) 忠实中文原意，不增删关键信息；" +
        "3) 简短自然，符合 WhatsApp 阅读习惯（不超过 90 词）；" +
        "4) 术语 FOB/MOQ/PI/CE/INMETRO/IP65/20GP/40HQ 保留原文；" +
        "5) 不编造中文里没有的数字或承诺；" +
        style +
        "7) 只输出改写后的消息正文，不要任何解释、引号或前后缀。";
    }
  };
})();
